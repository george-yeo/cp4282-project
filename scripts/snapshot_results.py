"""Copy the small result files of every finished run into results/, so the numbers in the report
can be checked, and the figures regenerated, without retraining.

For each run folder under runs/ and runs_*/ this keeps: spec.json, config.yaml (with the two
machine-specific paths replaced), DONE (the run's summary metrics), final.runlog.json (training
log: evaluations, densify events, b statistics, timing), final.beta.npz (the learned b of every
splat) and the per-view test/val metrics. Renders and .ply models are left out: they are large
and are regenerated by training.

    python scripts/snapshot_results.py            # writes results/
"""

import argparse
import csv
import io
import shutil
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
KEEP = ("spec.json", "DONE", "final.runlog.json", "final.beta.npz", "test_metrics.csv",
        "val_metrics.csv")
TOP_LEVEL = ("chosen.json", "sigma.json", "summary.csv")


def portable_config(src: Path, run: str) -> str:
    """config.yaml with paths that do not name the machine it was run on."""
    config = yaml.safe_load(src.read_text())
    paths = config.get("paths", {})
    if paths.get("data"):
        paths["data"] = "<data-root>/" + Path(str(paths["data"]).replace("\\", "/")).name
    if paths.get("output"):
        paths["output"] = f"{run}/final.png"
    if paths.get("init_ply"):
        parts = Path(str(paths["init_ply"]).replace("\\", "/")).parts
        paths["init_ply"] = "/".join(parts[-2:])
    return yaml.safe_dump(config, sort_keys=False)


def portable_metrics(src: Path) -> str:
    """A metrics CSV whose `file` column names the frame relative to the scene folder. Runs on a
    subset of the training views record an absolute path there."""
    out = []
    with src.open(newline="") as f:
        reader = csv.DictReader(f)
        buffer = io.StringIO()
        writer = csv.DictWriter(buffer, fieldnames=reader.fieldnames, lineterminator="\n")
        writer.writeheader()
        for row in reader:
            parts = row["file"].replace("\\", "/").split("/")
            row["file"] = "./" + "/".join(parts[-2:])
            writer.writerow(row)
        out.append(buffer.getvalue())
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(ROOT / "results"))
    args = ap.parse_args()
    out = Path(args.out)
    folders = sorted(p for p in ROOT.iterdir()
                     if p.is_dir() and (p.name == "runs" or p.name.startswith("runs_"))
                     and p.name != "runs_smoke")
    total = 0
    for folder in folders:
        count = 0
        for run in sorted(p for p in folder.iterdir() if p.is_dir() and (p / "DONE").exists()):
            dst = out / folder.name / run.name
            dst.mkdir(parents=True, exist_ok=True)
            for name in KEEP:
                if not (run / name).exists():
                    continue
                if name.endswith("_metrics.csv"):
                    (dst / name).write_text(portable_metrics(run / name), newline="\n")
                else:
                    shutil.copyfile(run / name, dst / name)
            (dst / "config.yaml").write_text(portable_config(run / "config.yaml", run.name),
                                             newline="\n")
            count += 1
        for name in TOP_LEVEL:
            if (folder / name).exists():
                (out / folder.name).mkdir(parents=True, exist_ok=True)
                shutil.copyfile(folder / name, out / folder.name / name)
        print(f"{folder.name}: {count} runs")
        total += count
    print(f"{total} runs copied to {out}")


if __name__ == "__main__":
    main()
